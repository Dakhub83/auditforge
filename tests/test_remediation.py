"""Remediation drafts: which drafts each failing check produces, safe templating, CLI guards."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from auditforge.cli import app
from auditforge.remediation import drafts as rem
from tests.conftest import FIXTURES
from tests.test_local_git import needs_git, repo, run_cli  # noqa: F401  (repo is a fixture)

runner = CliRunner()


def iac_report(tmp_path: Path) -> Path:
    runner.invoke(app, [
        "check", "iac", "--results", str(FIXTURES / "iac" / "checkov_terraform.json"),
        "--results", str(FIXTURES / "iac" / "kube_linter.sarif"), "--target", "payments-infra",
        "--out", str(tmp_path / "evidence"), "--db", str(tmp_path / "auditforge.db"),
    ])  # fmt: skip
    (path,) = (tmp_path / "evidence").glob("*/report.json")
    return path


def remediate(report: Path, tmp_path: Path, *extra: str):
    return runner.invoke(app, ["remediate", str(report), "--out", str(tmp_path / "remediation"), *extra])


def test_iac_report_produces_the_right_drafts(tmp_path: Path) -> None:
    doc = json.loads(iac_report(tmp_path).read_text(encoding="utf-8"))
    drafts = {d.draft_id: d for d in rem.build(doc)}
    # IAC-BAK passed, so no versioning draft; IAC-CFG has no template.
    assert set(drafts) == {
        "s3_encryption", "encryption_policy", "network_policy", "s3_access_logging",
        "kubernetes_privilege_policy",
    }  # fmt: skip
    enc = drafts["s3_encryption"].content
    assert 'resource "aws_s3_bucket_server_side_encryption_configuration" "customer_data"' in enc
    assert "aws_s3_bucket.logs" not in enc  # the suppressed rule on the logs bucket is not an exception
    assert drafts["network_policy"].triggers == ["IAC-NET FAIL"]


def test_every_template_renders_completely() -> None:
    finding = {"check_id": "?", "status": "FAIL", "observed": {"items": [
        {"outcome": "exception", "resource": "aws_s3_bucket.data", "rule_id": "R1", "rule_name": "n",
         "pull_request": 7, "sha": "a" * 40},
    ]}}  # fmt: skip
    for spec in rem.load_index().values():
        report = {"run_id": "r", "target": {"repo": "acme/api", "branch": "main"},
                  "findings": [{**finding, "check_id": spec["checks"][0]}]}  # fmt: skip
        (draft,) = [d for d in rem.build(report) if d.output == spec["output"]]
        assert "@{" not in draft.content, spec["output"]
        assert "DRAFT generated by AuditForge" in draft.content
        if draft.kind == "python":
            compile(draft.content, draft.output, "exec")


def test_unsafe_resource_names_are_not_templated() -> None:
    items = [
        {"outcome": "exception", "resource": 'aws_s3_bucket.x" } evil {', "rule_id": "R"},
        {"outcome": "exception", "resource": "aws_s3_bucket.ok", "rule_id": "R"},
    ]
    finding = {"check_id": "IAC-ENC", "status": "FAIL", "observed": {"items": items}}
    report = {"run_id": "r", "target": {}, "findings": [finding]}
    (enc,) = [d for d in rem.build(report) if d.draft_id == "s3_encryption"]
    assert "evil" not in enc.content and '"ok"' in enc.content
    assert enc.skipped and "not safe" in enc.skipped[0]
    assert "## Not templated" in rem.readme(report, [enc])


