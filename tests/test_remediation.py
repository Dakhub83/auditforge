@needs_git
def test_cli_git_report_drafts_branch_protection_and_evidence_script(repo: Path, tmp_path: Path) -> None:
    run_cli(repo, tmp_path)
    (report,) = (tmp_path / "evidence").glob("*/report.json")
    result = remediate(report, tmp_path)
    assert result.exit_code == 0, result.output
    assert "nothing was applied" in result.output
    out = tmp_path / "remediation" / json.loads(report.read_text(encoding="utf-8"))["run_id"]
    assert {p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file()} == {
        "README.md", "terraform/github_branch_protection.tf", "policy/branch_protection.rego",
        "scripts/collect_pr_evidence.py",
    }  # fmt: skip
    script = (out / "scripts" / "collect_pr_evidence.py").read_text(encoding="utf-8")
    assert "PULL_REQUESTS = [7, 8]" in script  # from the fixture repo's "#7" and "#8" subjects
    assert remediate(report, tmp_path).exit_code == 2  # no silent overwrite
    assert remediate(report, tmp_path, "--force").exit_code == 0


@needs_git
def test_cli_refuses_tampered_and_gap_reports(repo: Path, tmp_path: Path) -> None:
    run_cli(repo, tmp_path)
    (report,) = (tmp_path / "evidence").glob("*/report.json")
    (log,) = report.parent.glob("raw/first_parent_log.txt")
    original = log.read_bytes()
    log.write_text("edited", encoding="utf-8")
    tampered = remediate(report, tmp_path)
    assert tampered.exit_code == 2 and "unverified report" in tampered.output
    log.write_bytes(original)

    scope = tmp_path / "scope.yaml"
    runner.invoke(app, ["scope", "init", "--framework", "SOC2", "--out", str(scope)])
    runner.invoke(
        app,
        [
            "gap",
            "--scope",
            str(scope),
            "--out",
            str(tmp_path / "gap"),
            "--db",
            str(tmp_path / "auditforge.db"),
        ],
    )
    (gap_report,) = (tmp_path / "gap").glob("*/gap-report.json")
    result = remediate(gap_report, tmp_path)
    assert result.exit_code == 2 and "check reports" in result.output


def test_cli_nothing_to_draft(tmp_path: Path) -> None:
    passing = tmp_path / "pass.sarif"
    result_ok = {"ruleId": "r", "kind": "pass", "message": {"text": "Ensure encryption"}}
    sarif = {"version": "2.1.0", "runs": [{"tool": {"driver": {"name": "x"}}, "results": [result_ok]}]}
    passing.write_text(json.dumps(sarif), encoding="utf-8")
    runner.invoke(app, ["check", "iac", "--results", str(passing), "--out", str(tmp_path / "evidence"),
                        "--db", str(tmp_path / "auditforge.db")])  # fmt: skip
    (report,) = (tmp_path / "evidence").glob("*/report.json")
    result = remediate(report, tmp_path)
    assert result.exit_code == 0 and "nothing to draft" in result.output
